package provider

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/booldefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"

	"github.com/mailchannels/terraform-provider-mailchannels/internal/client"
)

var (
	_ resource.Resource                = &subAccountResource{}
	_ resource.ResourceWithConfigure   = &subAccountResource{}
	_ resource.ResourceWithImportState = &subAccountResource{}
)

// NewSubAccountResource returns the mailchannels_sub_account resource.
func NewSubAccountResource() resource.Resource { return &subAccountResource{} }

type subAccountResource struct{ client *client.Client }

type subAccountModel struct {
	ID          types.String `tfsdk:"id"`
	Handle      types.String `tfsdk:"handle"`
	CompanyName types.String `tfsdk:"company_name"`
	Enabled     types.Bool   `tfsdk:"enabled"`
}

func (r *subAccountResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_sub_account"
}

func (r *subAccountResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A sub-account of the parent account whose API key configures the provider. " +
			"Use sub-accounts to separate environments or customers. Set its monthly send limit with " +
			"`mailchannels_sub_account_limit`.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "The handle.",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"handle": schema.StringAttribute{
				MarkdownDescription: "Unique handle, 3 to 128 lower-case letters and digits. Generated by MailChannels when omitted. " +
					"Changing it replaces the sub-account.",
				Optional: true,
				Computed: true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
					stringplanmodifier.RequiresReplaceIfConfigured(),
				},
			},
			"company_name": schema.StringAttribute{
				MarkdownDescription: "Display name, 3 to 128 characters. The Email API cannot rename a sub-account, so " +
					"changing it replaces the sub-account.",
				Required:      true,
				PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()},
			},
			"enabled": schema.BoolAttribute{
				MarkdownDescription: "Whether the sub-account can send. `false` suspends it. Defaults to `true`.",
				Optional:            true,
				Computed:            true,
				Default:             booldefault.StaticBool(true),
			},
		},
	}
}

func (r *subAccountResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = clientFrom(req.ProviderData, &resp.Diagnostics)
}

func (r *subAccountResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan subAccountModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	created, err := r.client.CreateSubAccount(ctx, client.CreateSubAccountRequest{
		CompanyName: plan.CompanyName.ValueString(),
		Handle:      plan.Handle.ValueString(),
	})
	if err != nil {
		resp.Diagnostics.AddError("Creating sub-account", err.Error())
		return
	}
	plan.ID = types.StringValue(created.Handle)
	plan.Handle = types.StringValue(created.Handle)
	// Save the sub-account before suspending it, so a failure leaves it in state.
	enabled := plan.Enabled.ValueBool()
	plan.Enabled = types.BoolValue(created.Enabled)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() || created.Enabled == enabled {
		return
	}
	if err := r.client.SetSubAccountEnabled(ctx, created.Handle, enabled); err != nil {
		resp.Diagnostics.AddError("Setting sub-account enabled", err.Error())
		return
	}
	plan.Enabled = types.BoolValue(enabled)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *subAccountResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state subAccountModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	account, err := r.client.GetSubAccount(ctx, state.Handle.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Reading sub-account", err.Error())
		return
	}
	if account == nil {
		resp.State.RemoveResource(ctx)
		return
	}
	state.ID = types.StringValue(account.Handle)
	state.Handle = types.StringValue(account.Handle)
	// company_name is optional in the API's response; keep the known value
	// rather than plan a replacement when it is missing.
	if account.CompanyName != "" {
		state.CompanyName = types.StringValue(account.CompanyName)
	}
	state.Enabled = types.BoolValue(account.Enabled)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *subAccountResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state subAccountModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !plan.Enabled.Equal(state.Enabled) {
		if err := r.client.SetSubAccountEnabled(ctx, state.Handle.ValueString(), plan.Enabled.ValueBool()); err != nil {
			resp.Diagnostics.AddError("Setting sub-account enabled", err.Error())
			return
		}
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *subAccountResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state subAccountModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteSubAccount(ctx, state.Handle.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Deleting sub-account", err.Error())
	}
}

func (r *subAccountResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("handle"), req.ID)...)
}
